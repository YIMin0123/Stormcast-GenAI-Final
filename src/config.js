// 總經驗 exp 是第幾級：{ lv 等級, into 這一級已經累積多少, need 升下一級要多少 }
export function levelOf(exp) {
  let lv = 1, left = Math.max(0, Math.floor(exp || 0));
  while (lv < LEVEL.max && left >= LEVEL.need(lv)) { left -= LEVEL.need(lv); lv++; }
  return { lv, into: left, need: LEVEL.need(lv) };
}

